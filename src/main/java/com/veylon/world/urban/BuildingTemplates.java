package com.veylon.world.urban;

import com.veylon.util.Vec3i;
import com.veylon.world.BlockType;
import com.veylon.world.urban.BuildingPlan.Family;
import com.veylon.world.urban.BuildingPlan.Fixture;
import com.veylon.world.urban.BuildingPlan.FixtureKind;
import com.veylon.world.urban.BuildingPlan.Floor;
import com.veylon.world.urban.BuildingPlan.Function;
import com.veylon.world.urban.BuildingPlan.Room;
import com.veylon.world.urban.BuildingPlan.Stair;
import com.veylon.world.urban.BuildingPlan.Variant;

import java.util.ArrayList;
import java.util.List;

/** Frozen walk-ups and small shops, with separately versioned furnishing overlays. */
public final class BuildingTemplates {
    public static final int REVISION = UrbanRevision.BUILDING_TEMPLATE_WALKUPS;
    public static final int MAX_STOREYS = 5;
    /** Explicit A8 exemptions; none of these is generated by this catalogue. */
    public static final List<String> NON_ENTERABLE_INFRASTRUCTURE =
            List.of("utility-box-2x2", "open-bus-shelter", "kiosk-2x2");

    private BuildingTemplates() { }

    /** The original proposal and its furnished successor remain independently reproducible. */
    public static boolean supportsRevision(int revision) {
        return revision == REVISION || revision == UrbanRevision.BUILDING_TEMPLATE_FURNISHED
                || revision == UrbanRevision.BUILDING_TEMPLATE_SHAPED_STAIRS
                || revision == UrbanRevision.BUILDING_TEMPLATE_STARTER;
    }

    /** Low-level proposal; callers must validate it, or use {@link BuildingPlanner#plan}. */
    public static BuildingPlan propose(ParcelPlan parcel, int revision, Family family, Variant variant,
                                       int storeys, boolean basement, boolean minimal) {
        if (!supportsRevision(revision)) {
            throw new IllegalArgumentException("unsupported building template revision " + revision);
        }
        if (parcel.width() < 12 || parcel.width() > 32 || parcel.depth() < 12 || parcel.depth() > 32
                || storeys < 1 || storeys > Math.min(MAX_STOREYS, parcel.maxStoreys())
                || family == Family.SHOP && storeys > 2) {
            throw new IllegalArgumentException("building does not fit parcel/storey envelope");
        }
        BuildingPlan original = new Builder(parcel, family, variant, storeys, basement, minimal,
                f -> walkUp(family, f, minimal, parcel)).build();
        if (revision == REVISION) { return original; }
        BuildingPlan furnished = BuildingFurnishing.apply(original);
        if (revision == UrbanRevision.BUILDING_TEMPLATE_FURNISHED) { return furnished; }
        BuildingPlan shaped = BuildingStairShapes.apply(furnished);
        return revision == UrbanRevision.BUILDING_TEMPLATE_STARTER ? UrbanStarterSite.furnish(shaped) : shaped;
    }

    /**
     * Room functions of one storey of the shared skeleton. The front block beside the entry hall
     * is one room or, when split, an upper and a lower room; each back block (left, then right of
     * the hall) holds its first and second function as two rooms when split, otherwise as one.
     * Walls, doors, windows and reservations follow from the skeleton, never from the program.
     */
    record FloorProgram(List<Function> front, boolean splitFront, List<Function> left,
                        List<Function> right, boolean splitBack) {
        FloorProgram {
            front = List.copyOf(front); left = List.copyOf(left); right = List.copyOf(right);
            if (splitFront && front.size() != 2 || left.size() != 2 || right.size() != 2) {
                throw new IllegalArgumentException("a split block needs exactly two functions");
            }
        }
    }

    /** Frozen walk-up and shop functions of revision one, by storey. */
    static FloorProgram walkUp(Family family, int f, boolean minimal, ParcelPlan parcel) {
        boolean shop = family == Family.SHOP && f == 0;
        int depth = parcel.frontage().dx == 0 ? parcel.depth() : parcel.width();
        List<Function> front = f < 0 ? List.of(Function.BASEMENT_UTILITY)
                : shop ? List.of(Function.SHOP_FLOOR) : List.of(Function.BEDROOM, Function.BATHROOM);
        Function first = f < 0 ? Function.BASEMENT_STORAGE : shop ? Function.STOCKROOM : null;
        Function second = f < 0 ? Function.BASEMENT_UTILITY : shop ? Function.UTILITY : null;
        return new FloorProgram(front, !(minimal || shop || f < 0),
                List.of(first != null ? first : Function.KITCHEN, second != null ? second : Function.LIVING),
                List.of(first != null ? first : Function.STORAGE, second != null ? second : Function.UTILITY),
                !minimal && !shop && f >= 0 && depth >= 16);
    }

    static final class Builder {
        final ParcelPlan parcel;
        final Family family;
        final Variant variant;
        final int storeys, width, depth, entry, core;
        final boolean basement, minimal;
        final long id;
        final java.util.function.IntFunction<FloorProgram> program;
        final PlanVolume.Builder voxels;
        final List<Floor> floors = new ArrayList<>();
        final List<Fixture> fixtures = new ArrayList<>();
        final List<Vec3i> approaches = new ArrayList<>();
        final List<Stair> stairs = new ArrayList<>();

        Builder(ParcelPlan p, Family family, Variant variant, int storeys, boolean basement, boolean minimal,
                java.util.function.IntFunction<FloorProgram> program) {
            parcel = p; this.family = family; this.variant = variant; this.storeys = storeys;
            this.basement = basement; this.minimal = minimal; this.program = program;
            boolean alongX = p.frontage().dx == 0;
            width = alongX ? p.width() : p.depth();
            depth = alongX ? p.depth() : p.width();
            entry = (width - 2) / 2; core = entry + 2;
            id = UrbanIds.building(p.id(), 0);
            voxels = new PlanVolume.Builder(p.x0() - 1, p.z0() - 1, p.width() + 2, p.depth() + 2,
                    UrbanDatum.slabY(basement ? -1 : 0) - 1, UrbanDatum.slabY(storeys) + 3);
        }

        BuildingPlan build() {
            int lowest = basement ? -1 : 0;
            int bottom = UrbanDatum.slabY(lowest);
            for (int x = parcel.x0() - 1; x <= parcel.x1() + 1; x++) {
                for (int z = parcel.z0() - 1; z <= parcel.z1() + 1; z++) {
                    for (int y = bottom - 1; y <= UrbanDatum.STREET_Y; y++) {
                        voxels.set(x, y, z, parcel.contains(x, z) ? BlockType.CONCRETE : BlockType.PAVING);
                    }
                }
            }
            // Slabs and facade are one whole proposal, never per-chunk decisions.
            for (int f = lowest; f <= storeys; f++) {
                int slab = UrbanDatum.slabY(f);
                for (int u = 0; u < width; u++) {
                    for (int v = 0; v < depth; v++) {
                        put(u, slab, v, BlockType.CONCRETE);
                        for (int h = 1; h <= 3; h++) {
                            boolean edge = u == 0 || u == width - 1 || v == 0 || v == depth - 1;
                            put(u, slab + h, v, edge && (f < storeys || h == 1)
                                    ? BlockType.BRICK : BlockType.AIR);
                        }
                    }
                }
            }
            for (int f = lowest; f < storeys; f++) {
                floor(f);
            }
            roof();
            for (int f = lowest; f < storeys; f++) {
                switchback(f);
            }
            for (ParcelPlan.Entrance e : parcel.entrances()) {
                long room = UrbanIds.room(UrbanIds.floor(id, 0), 0);
                int slot = e.primary() ? 8 : 9;
                Vec3i at = new Vec3i(e.x(), 41, e.z());
                Vec3i outside = new Vec3i(e.outsideX(), 41, e.outsideZ());
                // Locked front door always has the unlatched rear route. No hypothetical key/tool.
                boolean locked = e.primary() && variant == Variant.OCCUPIED && !minimal;
                BlockType door = locked ? BlockType.METAL_DOOR : BlockType.WOOD_DOOR;
                for (int y = 41; y <= 42; y++) {
                    voxels.set(e.x(), y, e.z(), door).set(e.x2(), y, e.z2(), door);
                }
                fixtures.add(new Fixture(UrbanIds.fixture(room, slot), FixtureKind.DOOR,
                        at, 2, door, outside, locked));
                // Both leaves of the two-wide opening have stable independent ids.
                fixtures.add(new Fixture(UrbanIds.fixture(room, slot + 2), FixtureKind.DOOR,
                        new Vec3i(e.x2(), 41, e.z2()), 2, door,
                        new Vec3i(e.x2() + e.facing().dx, 41, e.z2() + e.facing().dz), locked));
                approaches.add(outside);
            }
            String size = width * depth <= 256 ? "compact" : width * depth <= 400 ? "standard" : "court";
            return new BuildingPlan(id, REVISION, (family == Family.SHOP ? "shop" : "apartment-" + size)
                    + (minimal ? "-minimal" : ""), family, variant, parcel, storeys, basement,
                    floors, fixtures, approaches, stairs, voxels.build());
        }

        void floor(int f) {
            int slab = UrbanDatum.slabY(f);
            long floorId = UrbanIds.floor(id, f);
            List<Room> rooms = new ArrayList<>();
            rooms.add(room(floorId, 0, List.of(Function.ENTRY), entry, 1, entry + 1, depth - 2, slab));
            rooms.add(room(floorId, 1, List.of(Function.CORRIDOR_STAIRS), 1, 7, entry - 2, 8, slab));
            rooms.add(room(floorId, 2, List.of(Function.CORRIDOR_STAIRS), entry + 3, 7, width - 2, 8, slab));
            rooms.add(room(floorId, 3, List.of(Function.CORRIDOR_STAIRS), core, 1, width - 2, 6, slab));
            wall(entry - 1, 1, entry - 1, depth - 2, slab);
            wall(entry + 2, 7, entry + 2, depth - 2, slab);
            FloorProgram plan = program.apply(f);
            if (!plan.splitFront()) {
                addRoom(rooms, floorId, 4, plan.front(), 1, 1, entry - 2, 6, slab, entry - 1, 4);
            } else {
                wall(1, 3, entry - 2, 3, slab);
                addRoom(rooms, floorId, 4, List.of(plan.front().get(0)), 1, 1, entry - 2, 2,
                        slab, entry - 1, 1);
                addRoom(rooms, floorId, 5, List.of(plan.front().get(1)), 1, 4, entry - 2, 6,
                        slab, entry - 1, 5);
            }
            int mid = (9 + depth - 2) / 2;
            for (int side = 0; side < 2; side++) {
                int a = side == 0 ? 1 : entry + 3, b = side == 0 ? entry - 2 : width - 2;
                int doorU = side == 0 ? entry - 1 : entry + 2;
                int index = side == 0 ? 6 : 8;
                List<Function> back = side == 0 ? plan.left() : plan.right();
                Function first = back.get(0), second = back.get(1);
                if (plan.splitBack()) {
                    wall(a, mid, b, mid, slab);
                    addRoom(rooms, floorId, index, List.of(first), a, 9, b, mid - 1, slab, doorU, 9);
                    addRoom(rooms, floorId, index + 1, List.of(second), a, mid + 1, b, depth - 2,
                            slab, doorU, mid + 1);
                } else {
                    addRoom(rooms, floorId, index, first == second ? List.of(first) : List.of(first, second),
                            a, 9, b, depth - 2, slab, doorU, 9);
                }
            }
            // The cross hall is two wide; doors in the separating walls keep it continuous.
            door(UrbanIds.room(floorId, 1), entry - 1, 7, slab, entry, 7);
            door(UrbanIds.room(floorId, 2), entry + 2, 7, slab, entry + 1, 7);
            floors.add(new Floor(floorId, f, slab, rooms, pos(core, slab + 1, 1)));
        }

        void addRoom(List<Room> rooms, long floor, int index, List<Function> functions,
                     int a, int c, int b, int d, int slab, int doorU, int doorV) {
            Room room = room(floor, index, functions, a, c, b, d, slab);
            rooms.add(room);
            int insideU = doorU < a ? a : b;
            door(room.id(), doorU, doorV, slab, insideU, doorV);
            int centreV = (c + d) / 2;
            int windowU = a == 1 ? 0 : width - 1;
            if (slab >= UrbanDatum.STREET_Y) {
                BlockType window = variant == Variant.DAMAGED ? BlockType.BROKEN_WINDOW : BlockType.WINDOW;
                put(windowU, slab + 2, centreV, window);
                put(windowU, slab + 3, centreV, window);
                fixtures.add(new Fixture(UrbanIds.fixture(room.id(), 1), FixtureKind.WINDOW,
                        pos(windowU, slab + 2, centreV), 2, window,
                        // Stand one cell in from the furniture line, still within F's reach.
                        pos(windowU == 0 ? 2 : width - 3, slab + 1, centreV), false));
            }
            if (!minimal) {
                BlockType container = functions.contains(Function.KITCHEN) || functions.contains(Function.BATHROOM)
                        ? BlockType.CABINET : functions.contains(Function.UTILITY) ? BlockType.LOCKER : BlockType.SHELF;
                // Opposite the door; a clear cell between furniture and the corridor is reserved.
                int furnitureU = a == 1 ? a : b;
                int targetU = a == 1 ? a + 1 : b - 1;
                put(furnitureU, slab + 1, d, container);
                fixtures.add(new Fixture(UrbanIds.fixture(room.id(), 2), FixtureKind.CONTAINER,
                        pos(furnitureU, slab + 1, d), 1, container, pos(targetU, slab + 1, d), false));
                if (variant == Variant.OCCUPIED && b - a >= 5 && d - c >= 3) {
                    put(furnitureU, slab + 1, c + 1, BlockType.TABLE);
                    fixtures.add(new Fixture(UrbanIds.fixture(room.id(), 3), FixtureKind.FURNITURE,
                            pos(furnitureU, slab + 1, c + 1), 1, BlockType.TABLE,
                            pos(targetU, slab + 1, c + 1), false));
                }
            }
            fixtures.add(new Fixture(UrbanIds.fixture(room.id(), 4), FixtureKind.QUEST,
                    room.anchor(), 1, BlockType.AIR, room.anchor(), false));
        }

        Room room(long floor, int index, List<Function> functions, int a, int c, int b, int d, int slab) {
            Vec3i first = pos(a, slab + 1, c), last = pos(b, slab + 1, d);
            ParcelPlan.Rect rect = new ParcelPlan.Rect(Math.min(first.x(), last.x()), Math.min(first.z(), last.z()),
                    Math.max(first.x(), last.x()), Math.max(first.z(), last.z()));
            return new Room(UrbanIds.room(floor, index), functions, rect, pos((a + b) / 2, slab + 1, c));
        }

        void door(long room, int u, int v, int slab, int targetU, int targetV) {
            put(u, slab + 1, v, BlockType.WOOD_DOOR);
            put(u, slab + 2, v, BlockType.WOOD_DOOR);
            fixtures.add(new Fixture(UrbanIds.fixture(room, 0), FixtureKind.DOOR,
                    pos(u, slab + 1, v), 2, BlockType.WOOD_DOOR, pos(targetU, slab + 1, targetV), false));
        }

        void roof() {
            long floor = UrbanIds.floor(id, storeys);
            int slab = UrbanDatum.slabY(storeys);
            Room roof = room(floor, 0, List.of(Function.UTILITY), 1, 1, width - 2, depth - 2, slab);
            floors.add(new Floor(floor, storeys, slab, List.of(roof), pos(core, slab + 1, 1)));
            fixtures.add(new Fixture(UrbanIds.fixture(roof.id(), 4), FixtureKind.QUEST,
                    pos(entry, slab + 1, depth - 2), 1, BlockType.AIR,
                    pos(entry, slab + 1, depth - 2), false));
        }

        void switchback(int f) {
            int slab = UrbanDatum.slabY(f);
            // Two-wide flights, two rises each, a two-deep intermediate landing.
            // Single-voxel treads (not solid fill) preserve headroom between stacked flights.
            for (int u = core; u < core + 4; u++) {
                for (int v = 2; v <= 6; v++) { put(u, slab + 4, v, BlockType.AIR); }
            }
            for (int u = core; u < core + 4; u++) {
                for (int v = 4; v <= 5; v++) { put(u, slab + 2, v, BlockType.STAIRS); }
                put(u, slab + 4, 1, BlockType.CONCRETE);
            }
            for (int u = core; u < core + 2; u++) {
                put(u, slab + 1, 2, BlockType.STAIRS);
                put(u, slab + 2, 3, BlockType.STAIRS);
            }
            for (int u = core + 2; u < core + 4; u++) {
                put(u, slab + 3, 3, BlockType.STAIRS);
                put(u, slab + 4, 2, BlockType.STAIRS);
            }
            List<Vec3i> route = List.of(pos(core, slab + 1, 1), pos(core, slab + 2, 2),
                    pos(core, slab + 3, 3), pos(core, slab + 3, 4), pos(core + 1, slab + 3, 4),
                    pos(core + 2, slab + 3, 4), pos(core + 2, slab + 4, 3),
                    pos(core + 2, slab + 5, 2), pos(core + 2, slab + 5, 1),
                    pos(core + 1, slab + 5, 1), pos(core, slab + 5, 1));
            stairs.add(new Stair(f, route));
        }

        void wall(int a, int c, int b, int d, int slab) {
            for (int u = a; u <= b; u++) {
                for (int v = c; v <= d; v++) {
                    for (int h = 1; h <= 3; h++) { put(u, slab + h, v, BlockType.PLASTER); }
                }
            }
        }

        void put(int u, int y, int v, BlockType block) {
            Vec3i p = pos(u, y, v);
            voxels.set(p.x(), y, p.z(), block);
        }

        Vec3i pos(int u, int y, int v) {
            return switch (parcel.frontage()) {
                case NORTH -> new Vec3i(parcel.x0() + u, y, parcel.z0() + v);
                case SOUTH -> new Vec3i(parcel.x0() + u, y, parcel.z1() - v);
                case WEST -> new Vec3i(parcel.x0() + v, y, parcel.z0() + u);
                case EAST -> new Vec3i(parcel.x1() - v, y, parcel.z0() + u);
            };
        }
    }
}
